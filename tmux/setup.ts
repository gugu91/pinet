import { copyFile, lstat, mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { constants } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { randomUUID } from "node:crypto";
import { fileURLToPath } from "node:url";
import { ACK, ATTENTION, type Tmux } from "./transport.ts";

export const HOOK = "pane-focus-in[1079]";
const BEGIN = "# BEGIN @pinet/tmux managed include";
const END = "# END @pinet/tmux managed include";
export const OPTIONS = [
  "window-status-format",
  "window-status-current-format",
  "status-right",
  "focus-events",
] as const;
type Option = (typeof OPTIONS)[number];
export type Snapshot = Record<Option, string>;
export interface Installation {
  version: 1;
  config: string;
  includePath: string;
  block: string;
  include: string;
  before: Snapshot;
  applied: Snapshot;
  configExisted: boolean;
  hook: string;
}
export interface SetupPaths {
  config: string;
  include: string;
  manifest: string;
}
export function setupPaths(home = homedir()): SetupPaths {
  const directory = join(home, ".config", "pinet", "tmux");
  return {
    config: join(home, ".tmux.conf"),
    include: join(directory, "integration.conf"),
    manifest: join(directory, "installation.json"),
  };
}
export function shellQuote(text: string): string {
  // eslint-disable-next-line no-control-regex -- Executable paths cannot contain terminal/config control characters.
  if (/[\u0000-\u001f\u007f]/.test(text))
    throw new Error("Control characters are not allowed in executable paths");
  return `'${text.replaceAll("'", `'"'"'`)}'`;
}
export function tmuxQuote(text: string): string {
  return JSON.stringify(text).replaceAll("$", "\\$");
}
export function commandPaths(
  base = import.meta.url,
  executable = process.execPath,
): { status: string; rex: string } {
  // Published code invokes sibling JavaScript; source previews invoke TypeScript.
  const suffix = base.endsWith(".ts") ? "ts" : "js";
  const status = fileURLToPath(new URL(`./status.${suffix}`, base));
  const rex = fileURLToPath(new URL(`./rex-cli.${suffix}`, base));
  const node = shellQuote(executable);
  return { status: `${node} ${shellQuote(status)}`, rex: `${node} ${shellQuote(rex)}` };
}
export function integration(
  before: Snapshot,
  paths: SetupPaths,
  commands = commandPaths(),
): Installation {
  const label = `#(${commands.status} #{q:socket_path} window #{window_id})`;
  const format = (original: string) =>
    /#W|#\{window_name\}/.test(original)
      ? original.replace(/#W|#\{window_name\}/g, label)
      : `${original} ${label}`;
  const applied: Snapshot = {
    "window-status-format": format(before["window-status-format"]),
    "window-status-current-format": format(before["window-status-current-format"]),
    "status-right": `#(${commands.rex} #{q:socket_path} #{client_pid} tick)${before["status-right"]}`,
    "focus-events": "on",
  };
  const focus = `set-option -p -F ${ACK} '#{${ATTENTION}}'`;
  const include = `# Generated by /tmux setup; remove with /tmux uninstall.\n${OPTIONS.map((key) => `set-option -g ${key} ${tmuxQuote(applied[key])}`).join("\n")}\nset-hook -g '${HOOK}' ${tmuxQuote(focus)}\n`;
  const block = `${BEGIN}\nsource-file ${tmuxQuote(paths.include)}\n${END}\n`;
  return {
    version: 1,
    config: paths.config,
    includePath: paths.include,
    block,
    include,
    before,
    applied,
    configExisted: false,
    hook: "",
  };
}
export function removeBlock(config: string, block: string): string {
  if (!config.includes(block) || config.indexOf(block) !== config.lastIndexOf(block))
    throw new Error("Managed source block was edited; refusing to remove unrelated configuration");
  return config.replace(block, "");
}
export function parseInstallation(text: string): Installation {
  const data: Installation = JSON.parse(text);
  if (
    !data ||
    data.version !== 1 ||
    typeof data.config !== "string" ||
    typeof data.includePath !== "string" ||
    typeof data.block !== "string" ||
    typeof data.include !== "string" ||
    typeof data.configExisted !== "boolean" ||
    typeof data.hook !== "string" ||
    !data.before ||
    !data.applied ||
    OPTIONS.some(
      (key) => typeof data.before[key] !== "string" || typeof data.applied[key] !== "string",
    )
  ) {
    throw new Error("Invalid @pinet/tmux installation manifest");
  }
  return data;
}
export async function optionalFile(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return undefined;
    throw error;
  }
}
export async function installation(paths: SetupPaths): Promise<Installation | undefined> {
  const text = await optionalFile(paths.manifest);
  if (text === undefined) return undefined;
  const data = parseInstallation(text);
  if (data.config !== paths.config || data.includePath !== paths.include)
    throw new Error("Installation manifest belongs to another configuration path");
  return data;
}
export async function snapshot(tmux: Tmux): Promise<Snapshot> {
  const entries = await Promise.all(
    OPTIONS.map(async (key) => [key, await tmux.run(["show-options", "-gqv", key])] as const),
  );
  return Object.fromEntries(entries) as Snapshot;
}
export async function writeConfig(path: string, text: string): Promise<void> {
  const current = await lstat(path).catch((error: Error & { code?: string }) => {
    if (error.code === "ENOENT") return undefined;
    throw error;
  });
  if (current && !current.isFile())
    throw new Error(
      "Automatic setup requires a regular tmux config file (not a symlink); use the manual include instructions instead",
    );
  const temporary = `${path}.${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, text, { flag: "wx", mode: current?.mode ?? 0o600 });
    await rename(temporary, path);
  } finally {
    await rm(temporary, { force: true });
  }
}
export async function preview(tmux: Tmux, paths: SetupPaths): Promise<Installation> {
  if (await installation(paths))
    throw new Error("Already installed; use /tmux doctor or uninstall before setting up again");
  const config = await optionalFile(paths.config);
  if (config?.includes(BEGIN))
    throw new Error(
      "An existing managed include has no matching manifest; inspect it before setup",
    );
  if ((await tmux.run(["show-hooks", "-g", HOOK])).trim() !== HOOK)
    throw new Error(`Hook slot ${HOOK} is occupied; refusing to replace it`);
  const result = integration(await snapshot(tmux), paths);
  result.configExisted = config !== undefined;
  return result;
}
export async function install(tmux: Tmux, paths: SetupPaths, plan: Installation): Promise<void> {
  const before = await snapshot(tmux);
  if (OPTIONS.some((key) => before[key] !== plan.before[key]))
    throw new Error("tmux options changed during confirmation; preview setup again");
  const config = await optionalFile(paths.config);
  if (config?.includes(BEGIN)) throw new Error("A managed include is already present");
  if ((await tmux.run(["show-hooks", "-g", HOOK])).trim() !== HOOK)
    throw new Error("Focus hook changed during confirmation; preview setup again");
  plan.configExisted = config !== undefined;
  await mkdir(dirname(paths.manifest), { recursive: true });
  await writeFile(paths.manifest, JSON.stringify(plan, null, 2) + "\n", {
    flag: "wx",
    mode: 0o600,
  });
  let wroteInclude = false;
  try {
    if (config !== undefined)
      await copyFile(
        paths.config,
        `${paths.config}.pinet-tmux-${randomUUID()}.bak`,
        constants.COPYFILE_EXCL,
      );
    await writeFile(paths.include, plan.include, { flag: "wx", mode: 0o600 });
    wroteInclude = true;
    await writeConfig(
      paths.config,
      `${config ?? ""}${config && !config.endsWith("\n") ? "\n" : ""}${plan.block}`,
    );
    await tmux.run(["source-file", paths.include]);
    plan.hook = await tmux.run(["show-hooks", "-g", HOOK]);
    await writeFile(paths.manifest, JSON.stringify(plan, null, 2) + "\n", { mode: 0o600 });
  } catch (error) {
    // Ownership spans files and the live server: restore the previewed state on a failed apply.
    const failedOptions = await snapshot(tmux);
    for (const key of OPTIONS) {
      if (failedOptions[key] === plan.applied[key])
        await tmux.run(["set-option", "-g", key, plan.before[key]]);
    }
    if (plan.hook && (await tmux.run(["show-hooks", "-g", HOOK])) === plan.hook)
      await tmux.run(["set-hook", "-gu", HOOK]);
    const changed = await optionalFile(paths.config);
    if (changed?.includes(plan.block)) {
      const cleaned = removeBlock(changed, plan.block);
      if (!plan.configExisted && !cleaned.trim()) await rm(paths.config, { force: true });
      else await writeConfig(paths.config, cleaned);
    }
    if (wroteInclude && (await optionalFile(paths.include)) === plan.include)
      await rm(paths.include, { force: true });
    await rm(paths.manifest, { force: true });
    throw error;
  }
}
export async function uninstall(tmux: Tmux, paths: SetupPaths): Promise<void> {
  const saved = await installation(paths);
  if (!saved) return;
  const config = await optionalFile(paths.config);
  const include = await optionalFile(paths.include);
  if (include !== saved.include)
    throw new Error(
      "Generated include was edited; preserve it and resolve manually before uninstalling",
    );
  if (config === undefined) throw new Error("Managed tmux configuration is missing");
  const cleaned = removeBlock(config, saved.block);
  const current = await snapshot(tmux);
  for (const key of OPTIONS) {
    if (current[key] === saved.applied[key])
      await tmux.run(["set-option", "-g", key, saved.before[key]]);
  }
  const hook = await tmux.run(["show-hooks", "-g", HOOK]);
  // Only remove our exact indexed hook; preserve a replacement installed by the user.
  if (hook === saved.hook) await tmux.run(["set-hook", "-gu", HOOK]);
  if (!saved.configExisted && !cleaned.trim()) await rm(paths.config);
  else await writeConfig(paths.config, cleaned);
  await rm(paths.include);
  await rm(paths.manifest);
}
